#!/usr/bin/env node
// Sync the SimpleRobot programming manual into the app bundle.
//
// Source: the controller repo's docs/manual/ (manifest.json, chapters/*.md, figures/*.svg,
// screens/*.png, reference.json — see its README). Output: src/docs/content/ — plain TS
// modules that Metro bundles, so the in-app manual works offline:
//
//   manifest.ts           title, parts, chapter list (id, file stem, number, title, generated)
//   chapters/<id>.ts      each chapter's Markdown as a string
//   chapters/index.ts     id → Markdown
//   figures.ts            figure file → { svg, title, width, height } (SVG inlined for react-native-svg)
//   screens.ts            screenshot file → require("./screens/<file>")
//   screens/*.png         copied screenshots
//   reference.ts          instructions (normalised, see src/docs/types.ts), categories, error and
//                         problem codes, functions, properties, IO names, keywords
//
// A chapter whose Markdown file is not written yet is skipped (with a warning) unless the
// manifest marks it `generated` — those render from reference.json in the app.
//
// Usage (from SimpleRobotApp/):
//   node scripts/sync-manual.mjs                      # ../SimpleRobotController/docs/manual
//   node scripts/sync-manual.mjs --src <manual dir>   # any folder in the same layout
//
// The output is committed; re-run this after the manual changes and commit src/docs/content.

import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { basename, dirname, extname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const appRoot = resolve(here, "..");
const args = process.argv.slice(2);
const srcArg = args.indexOf("--src");
const SRC = resolve(srcArg >= 0 ? args[srcArg + 1] : join(appRoot, "..", "SimpleRobotController", "docs", "manual"));
const OUT = join(appRoot, "src", "docs", "content");

if (!existsSync(SRC)) {
  console.error(`sync-manual: no manual at ${SRC}`);
  process.exit(1);
}

const HEADER = "// GENERATED by scripts/sync-manual.mjs from the controller's docs/manual — do not edit.\n";
const readJson = (p, fallback) => (existsSync(p) ? JSON.parse(readFileSync(p, "utf8").replace(/^﻿/, "")) : fallback);
const listFiles = (dir, ext) => (existsSync(dir) ? readdirSync(dir).filter(f => extname(f).toLowerCase() === ext && statSync(join(dir, f)).isFile()).sort() : []);
const lit = v => JSON.stringify(v, null, 2);
const ident = s => "ch_" + s.replace(/[^A-Za-z0-9]/g, "_");
const asArray = v => (v == null ? [] : Array.isArray(v) ? v : [v]);
const blank = v => (v == null || v === "" ? undefined : v);
const text = v => (v == null ? "" : Array.isArray(v) ? v.join("\n") : String(v));

// ── Manifest + chapters ──────────────────────────────────────────────────────

const manifest = readJson(join(SRC, "manifest.json"), {});
const parts = asArray(manifest.parts).map(p => ({ id: String(p.id), title: String(p.title ?? p.id), chapters: asArray(p.chapters).map(String) }));
const partOf = id => parts.find(p => p.chapters.includes(id))?.id;
const chapterDir = join(SRC, "chapters");

// Manifest entries: { id, number, title, file, generated }. Without a manifest: every
// chapters/*.md in name order.
const entries = asArray(manifest.chapters).length
  ? asArray(manifest.chapters).map(c => (typeof c === "string" ? { file: c } : c))
  : listFiles(chapterDir, ".md").map(f => ({ file: `chapters/${f}` }));

const chapters = [];
entries.forEach((c, i) => {
  const fileName = c.file ? basename(String(c.file)) : "";
  const stem = fileName.replace(/\.md$/, "");
  const path = fileName ? join(chapterDir, fileName) : "";
  const exists = !!path && existsSync(path);
  const generated = c.generated ? String(c.generated) : undefined;
  if (!exists && !generated) { console.warn(`sync-manual: skipping ${c.id ?? stem} — ${c.file ?? "no file"} not written yet`); return; }
  const md = exists ? readFileSync(path, "utf8").replace(/^﻿/, "").replace(/\r\n?/g, "\n") : "";
  const m = /^(\d+|[A-Z])-(.+)$/.exec(stem);
  const h1 = /^#\s+(.+?)\s*#*\s*$/m.exec(md)?.[1];
  const id = String(c.id ?? (m ? m[2] : stem));
  chapters.push({
    id,
    file: stem || id,
    number: String(c.number ?? (m ? m[1].replace(/^0+(?=\d)/, "") : i + 1)),
    title: String(c.title ?? h1 ?? id.replace(/-/g, " ")),
    ...(partOf(id) ? { part: partOf(id) } : {}),
    ...(generated ? { generated } : {}),
    md,
  });
});

// ── Figures (SVG inlined) ────────────────────────────────────────────────────

const figureMeta = new Map();
for (const f of [...asArray(manifest.figures), ...asArray(manifest.screens)]) {
  const file = typeof f === "string" ? f : f.file ?? f.path ?? f.name;
  if (file) figureMeta.set(basename(String(file)), typeof f === "string" ? {} : f);
}

function cleanSvg(svg) {
  return svg
    .replace(/^﻿/, "")
    .replace(/<\?xml[^>]*\?>/g, "")
    .replace(/<!DOCTYPE[^>]*>/gi, "")
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/\r\n?/g, "\n")
    .trim();
}

function svgSize(svg) {
  const vb = /viewBox\s*=\s*["']\s*([-\d.]+)[\s,]+([-\d.]+)[\s,]+([\d.]+)[\s,]+([\d.]+)/i.exec(svg);
  const w = /<svg[^>]*\swidth\s*=\s*["']([\d.]+)/i.exec(svg);
  const h = /<svg[^>]*\sheight\s*=\s*["']([\d.]+)/i.exec(svg);
  return {
    width: vb ? Number(vb[3]) : w ? Number(w[1]) : 400,
    height: vb ? Number(vb[4]) : h ? Number(h[1]) : 300,
  };
}

const figures = {};
for (const file of listFiles(join(SRC, "figures"), ".svg")) {
  const svg = cleanSvg(readFileSync(join(SRC, "figures", file), "utf8"));
  const meta = figureMeta.get(file) ?? {};
  const title = meta.title ?? meta.caption ?? /<title>([^<]*)<\/title>/i.exec(svg)?.[1] ?? "";
  figures[file] = { svg, title, ...svgSize(svg), ...(/<style[\s>]/i.test(svg) ? { css: true } : {}) };
}

// ── Screens (copied, required) ───────────────────────────────────────────────

const screenFiles = [".png", ".jpg", ".jpeg", ".webp"].flatMap(e => listFiles(join(SRC, "screens"), e));

// ── Reference ────────────────────────────────────────────────────────────────

const ref = readJson(join(SRC, "reference.json"), {});

/** "Wait <ms> | Wait until …" → one line per form (a " | " at bracket depth 0 before a word). */
function splitSyntax(s) {
  const out = [];
  let depth = 0, from = 0;
  for (let i = 0; i < s.length; i++) {
    const c = s[i];
    if ("[(<{".includes(c)) depth++;
    else if ("])>}".includes(c)) depth = Math.max(0, depth - 1);
    else if (depth === 0 && s.startsWith(" | ", i) && /[A-Za-z@$]/.test(s[i + 3] ?? "")) {
      out.push(s.slice(from, i).trim());
      from = i + 3;
      i += 2;
    }
  }
  out.push(s.slice(from).trim());
  return out.filter(Boolean);
}

const fmtDefault = d => (d == null || d === "" ? undefined : typeof d === "string" ? d : typeof d === "boolean" ? (d ? "on" : "off") : JSON.stringify(d));

const steps = asArray(ref.steps).map(e => {
  const ex = e.example && typeof e.example === "object" ? e.example : null;
  return {
    type: String(e.type ?? e.keyword),
    keyword: String(e.keyword ?? e.type),
    aliases: asArray(e.aliases).map(String),
    name: String(e.name ?? e.block ?? e.label ?? e.type),
    category: String(e.category ?? "other"),
    ...(blank(e.categoryLabel) ? { categoryLabel: e.categoryLabel } : {}),
    syntax: asArray(e.syntax).flatMap(s => String(s).split("\n")).flatMap(splitSyntax),
    description: text(e.description),
    params: asArray(e.params).map(p => ({
      key: String(p.key ?? p.name),
      label: String(p.label ?? p.key ?? p.name),
      inText: String(p.inText ?? ""),
      type: String(p.type ?? p.kind ?? ""),
      kind: blank(p.kind),
      value: blank(p.value),
      unit: blank(p.unit),
      default: fmtDefault(p.default),
      min: p.min ?? undefined,
      max: p.max ?? undefined,
      required: p.required ? true : undefined,
      expression: p.expression ? true : undefined,
      options: asArray(p.options).length
        ? asArray(p.options).map(o => (typeof o === "object" ? { value: String(o.value), label: String(o.label ?? o.value) } : { value: String(o), label: String(o) }))
        : undefined,
      showIf: p.showIf ?? undefined,
      help: text(p.help ?? p.description),
      group: blank(p.group),
    })),
    notes: asArray(e.notes).map(text).filter(Boolean),
    errors: asArray(e.errors).map(x => (typeof x === "string"
      ? { code: "", when: x }
      : { code: String(x.code ?? ""), label: blank(x.label), catchable: x.catchable, when: text(x.when ?? x.description) })),
    example: ex ? text(ex.srs ?? ex.code) : text(e.example),
    exampleScreen: ex ? blank(ex.screen) : undefined,
    seeAlso: asArray(e.seeAlso).map(s => String(typeof s === "object" ? s.type ?? s.keyword : s)),
    background: e.background ?? undefined,
    chapter: blank(e.chapter),
  };
});

const categories = asArray(ref.categories).map(c => ({ key: String(c.key), label: String(c.label ?? c.key), ...(blank(c.description) ? { description: c.description } : {}) }));
const keywords = {
  statements: asArray(ref.keywords?.statements),
  flow: asArray(ref.keywords?.flow),
  declarations: asArray(ref.keywords?.declarations),
  values: asArray(ref.keywords?.values),
  attributes: asArray(ref.keywords?.attributes),
};

// ── Write ────────────────────────────────────────────────────────────────────

// Rewrite files in place (no rmdir: a running Metro watcher copes badly with a deleted and
// recreated folder) and drop the ones the manual no longer has at the end.
mkdirSync(join(OUT, "chapters"), { recursive: true });
mkdirSync(join(OUT, "screens"), { recursive: true });
const written = new Set();
const writeOut = (rel, content) => { written.add(rel); writeFileSync(join(OUT, rel), content); };

const gen = ref.generatedFrom ?? {};
writeOut("manifest.ts", `${HEADER}import type { ManualManifest } from "../types";

export const MANUAL_MANIFEST: ManualManifest = ${lit({
  title: manifest.title ?? "Programming Manual",
  subtitle: manifest.subtitle ?? "",
  version: gen.generatedAt ? `Language v${gen.languageVersion ?? "?"} · ${gen.generatedAt}` : manifest.version != null ? String(manifest.version) : "",
  parts,
  chapters: chapters.map(({ md, ...meta }) => meta),
})};
`);

for (const c of chapters) {
  writeOut(`chapters/${c.id}.ts`, `${HEADER}const md: string = ${JSON.stringify(c.md)};\nexport default md;\n`);
}
writeOut("chapters/index.ts", `${HEADER}${chapters.map(c => `import ${ident(c.id)} from "./${c.id}";`).join("\n")}

export const CHAPTER_MARKDOWN: Record<string, string> = {
${chapters.map(c => `  ${JSON.stringify(c.id)}: ${ident(c.id)},`).join("\n")}
};
`);

writeOut("figures.ts", `${HEADER}import type { ManualFigure } from "../types";

export const MANUAL_FIGURES: Record<string, ManualFigure> = ${lit(figures)};
`);

for (const f of screenFiles) { written.add(`screens/${f}`); copyFileSync(join(SRC, "screens", f), join(OUT, "screens", f)); }
writeOut("screens.ts", `${HEADER}import type { ImageSourcePropType } from "react-native";

export const MANUAL_SCREENS: Record<string, ImageSourcePropType> = {
${screenFiles.map(f => `  ${JSON.stringify(f)}: require("./screens/${f}"),`).join("\n")}
};
`);

writeOut("reference.ts", `${HEADER}import type { RefCategory, RefEntry, RefErrorCode, RefFunction, RefIo, RefKeywords, RefProblemCode, RefProperty } from "../types";

export const REFERENCE_CATEGORIES: RefCategory[] = ${lit(categories)};

export const REFERENCE: RefEntry[] = ${lit(steps)};

export const ERROR_CODES: RefErrorCode[] = ${lit(asArray(ref.errorCodes))};

export const PROBLEM_CODES: Record<string, RefProblemCode[]> = ${lit(ref.problemCodes ?? {})};

export const FUNCTIONS: RefFunction[] = ${lit(asArray(ref.functions))};

export const PROPERTIES: RefProperty[] = ${lit(asArray(ref.properties))};

export const IO_NAMES: RefIo[] = ${lit(asArray(ref.io))};

export const KEYWORDS: RefKeywords = ${lit(keywords)};
`);

for (const dir of ["", "chapters", "screens"]) {
  for (const f of readdirSync(join(OUT, dir))) {
    const rel = dir ? `${dir}/${f}` : f;
    if (statSync(join(OUT, rel)).isFile() && !written.has(rel)) rmSync(join(OUT, rel));
  }
}

console.log(`sync-manual: ${chapters.length} chapters, ${Object.keys(figures).length} figures, ${screenFiles.length} screens, ${steps.length} instructions`);
console.log(`  from ${SRC}`);
console.log(`  to   ${OUT}`);
