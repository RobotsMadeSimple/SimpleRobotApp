#!/usr/bin/env node
// Bundles the 3D cell viewer (three.js + GLTFLoader + OrbitControls + src/components/ui/cell3d/
// viewerCore.ts) into src/components/ui/cell3d/cell3dBundle.generated.ts — one IIFE, minified,
// exported as a string that cell3dHtml.ts (Cell3DView on native and web) and the display-page
// bridge (the "3D cell" widget) inline, so the viewer works offline on a robot's network.
// Re-run after changing anything under src/components/ui/cell3d/ that the viewer uses, or after a
// three.js upgrade:
//
//   npm run build:cell3d                 # write the bundle
//   node scripts/build-cell3d.mjs --check  # exit 1 if the committed bundle is stale

import { build } from "esbuild";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "src/components/ui/cell3d");
const out = join(dir, "cell3dBundle.generated.ts");

const result = await build({
  entryPoints: [join(dir, "webviewEntry.ts")],
  bundle: true,
  minify: true,
  format: "iife",
  target: "es2019",
  write: false,
  legalComments: "none",
  tsconfig: join(root, "tsconfig.json"),
  logLevel: "warning",
});
const js = result.outputFiles[0].text;
const hash = createHash("sha256").update(js).digest("hex").slice(0, 16);
// `</script` would end the inline <script> early; JSON.stringify keeps the rest a valid literal.
const literal = JSON.stringify(js).replace(/<\/script/gi, "<\\/script");
const three = JSON.parse(readFileSync(join(root, "node_modules/three/package.json"), "utf8")).version;
const file =
`// GENERATED by scripts/build-cell3d.mjs — do not edit. three.js ${three} + the 3D cell viewer
// (src/components/ui/cell3d/viewerCore.ts), inlined by cell3dHtml.ts and displayBridge.ts.
// ${(js.length / 1024).toFixed(0)} KB, sha ${hash}.
export const CELL3D_BUNDLE_HASH = "${hash}";
export const CELL3D_BUNDLE_JS: string = ${literal};
`;

if (process.argv.includes("--check")) {
  const cur = existsSync(out) ? readFileSync(out, "utf8") : "";
  const m = /CELL3D_BUNDLE_HASH = "([0-9a-f]+)"/.exec(cur);
  if (m?.[1] !== hash) { console.error(`cell3d bundle is stale (committed ${m?.[1] ?? "none"}, built ${hash}) — run npm run build:cell3d`); process.exit(1); }
  console.log(`cell3d bundle up to date (${hash})`);
} else {
  writeFileSync(out, file);
  console.log(`wrote ${out} (${(js.length / 1024).toFixed(0)} KB, ${hash})`);
}
