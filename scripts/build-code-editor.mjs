#!/usr/bin/env node
// Bundles the SRS code editor (CodeMirror 6 + src/components/ui/code-editor/editorCore.ts) for the
// native WebView into src/components/ui/code-editor/codeEditorBundle.generated.ts — one IIFE,
// minified, exported as a string that codeEditorHtml.ts inlines. Re-run after changing
// editorCore.ts, srsTokens.ts, srsCompletions.ts or bridge.ts, or after a CodeMirror upgrade:
//
//   node scripts/build-code-editor.mjs          # write the bundle
//   node scripts/build-code-editor.mjs --check  # exit 1 if the committed bundle is stale
//
// Web does not use the bundle: CodeEditor.web.tsx imports editorCore.ts directly through Metro.

import { build } from "esbuild";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "src/components/ui/code-editor");
const out = join(dir, "codeEditorBundle.generated.ts");

const result = await build({
  entryPoints: [join(dir, "webviewEntry.ts")],
  bundle: true,
  minify: true,
  format: "iife",
  target: "es2019",
  write: false,
  legalComments: "none",
  tsconfig: join(root, "tsconfig.json"),
  logLevel: "warning",
});
const js = result.outputFiles[0].text;
const hash = createHash("sha256").update(js).digest("hex").slice(0, 16);
// `</script` would end the inline <script> early; JSON.stringify keeps the rest a valid literal.
const literal = JSON.stringify(js).replace(/<\/script/gi, "<\\/script");
const file =
`// GENERATED by scripts/build-code-editor.mjs — do not edit. CodeMirror 6 + the SRS editor core
// for the native WebView (inlined by codeEditorHtml.ts). ${(js.length / 1024).toFixed(0)} KB, sha ${hash}.
export const CODE_EDITOR_BUNDLE_HASH = "${hash}";
export const CODE_EDITOR_BUNDLE_JS: string = ${literal};
`;

if (process.argv.includes("--check")) {
  const cur = existsSync(out) ? readFileSync(out, "utf8") : "";
  const m = /CODE_EDITOR_BUNDLE_HASH = "([0-9a-f]+)"/.exec(cur);
  if (m?.[1] !== hash) { console.error(`code editor bundle is stale (committed ${m?.[1] ?? "none"}, built ${hash}) — run node scripts/build-code-editor.mjs`); process.exit(1); }
  console.log(`code editor bundle up to date (${hash})`);
} else {
  writeFileSync(out, file);
  console.log(`wrote ${out} (${(js.length / 1024).toFixed(0)} KB, ${hash})`);
}
